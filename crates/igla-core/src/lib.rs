//! Расчётное ядро «ИГЛА» — сопло внешнего расширения по методу Ангелино.
//!
//! # Правила, на которых стоит этот крейт
//!
//! 1. **Только СИ.** Метры, паскали, кельвины, секунды, килограммы на моль.
//!    Бары, миллиметры и километры живут исключительно в [`project`] —
//!    на границе с файлом. Внутри решателя единиц в именах полей нет.
//! 2. **Никакого ввода-вывода.** Ядро не читает файлы, не разбирает аргументы
//!    и не рисует. Благодаря этому его одинаково зовут CLI, окно и Python.
//! 3. **Невалидный ввод — ошибка, а не молчаливая поправка.** Возвращаем
//!    [`Error`], а не подменяем ε = 0.8 на 1.05, как делал прототип.
//!
//! # Границы модели
//!
//! Реализован метод Ангелино (1964): приближённое построение центрального тела
//! по течению Прандтля–Майера от кромки, с постоянным γ, без пограничного слоя
//! и без характеристической сетки. Настоящий MOC — отдельный проект; [`gas`]
//! специально не переплетён с [`contour`], чтобы термодинамику можно было
//! забрать как есть.

